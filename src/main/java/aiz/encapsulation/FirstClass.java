package aiz.encapsulation;

public class FirstClass {


    // complete encapsulation
   private String box; // has the least access scope level - we can only access within the same class

    String name; // default - it has the most access level - we can access it from anywhere

    //  Partial encapsulation
    protected String firstName; // has a one step higher level that private in that we can access
    // it within the package, but not outside the package


    public String lastName;//  it has the most access level - we can access it from anywhere






    // encapsulated


    /**
     * 1. public
     * 2. private
     * 3. protected
     * 4. default
     */





}
