package vinitha.sms;

abstract public class Person {

    // Abstract class purpose is to help you re-used code in multiple classes
    // instead of repeating the same code in multiple classes

    String name;

    int age;

    String color;

    public Person(String name, int age, String color) {
        this.name = name;
        this.age = age;
        this.color = color;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getColor() {
        return color;
    }

    public void setColor(String color) {
        this.color = color;
    }

    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }
}
