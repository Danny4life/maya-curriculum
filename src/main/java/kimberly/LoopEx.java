package kimberly;

public class LoopEx {

    public static void main(String[] args) {

        // initialization = i = 1;
        // condition = i <= 5
        // increment / decrement = i++


        for(int i = 5; i > 0; i--){
            System.out.println(i);

            // 1
            // 2
            // 3
            // 4
            // 5


            // 5
            // 4
            // 3
            // 2
            // 1
        }









    }
}
